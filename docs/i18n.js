let currentLang = "tr";
try {
    const fromUrl = new URLSearchParams(window.location.search).get("lang");
    const stored = localStorage.getItem("napsak_lang");
    const browser = (navigator.language || "tr").toLowerCase().startsWith("tr") ? "tr" : "en";
    const pick = fromUrl || stored || browser;
    currentLang = I18N[pick] ? pick : "tr";
    if (fromUrl && I18N[fromUrl]) localStorage.setItem("napsak_lang", fromUrl);
} catch (e) { /* storage blocked: fall back to the browser language */ }

function t(key, vars) {
    let s = (I18N[currentLang] && I18N[currentLang][key]) || I18N.tr[key] || key;
    if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
    return s;
}

// Fills every [data-i18n*] element of the static page
function applyI18n(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
    root.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
    root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
    root.querySelectorAll("[data-i18n-alt]").forEach(el => { el.alt = t(el.dataset.i18nAlt); });
    root.querySelectorAll("[data-i18n-content]").forEach(el => { el.setAttribute("content", t(el.dataset.i18nContent)); });
    document.documentElement.lang = currentLang;
    document.title = t("meta.title");
}

function setLanguage(lang) {
    if (!I18N[lang]) return;
    try { localStorage.setItem("napsak_lang", lang); } catch (e) { /* ignore */ }
    window.location.reload();
}

applyI18n();
